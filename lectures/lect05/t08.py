# Нехай задано натуральне число 𝑁 і
# послідовність чисел 𝑎_1,…,𝑎_𝑁.
# (додатково припустимо, що принаймні одне з чисел більше -100500)
# Потрібно знайти max(𝑎_1,…,𝑎_𝑁 ).

# 1 4 55 7 5
# winner = 55

winner = -100500   # милиця!!!
N = int(input("N = ")) # скільки чисел вводиться з клавіатури
for _ in range(N): # тіло циклу виконається рівно N разів
    a = int(input("a = ")) # поточний член послідовності a_n
    if a > winner:
        winner = a

print(winner)



