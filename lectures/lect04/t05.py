# Знайти суму цифр заданого натурального числа

N = int(input("N = ")) # 256 : 2 + 5 + 6

# 256 = 2 * 10^2 + 5 * 10^1 + 6 * 10^0

# 256 // 10 = 25, 256 % 10 -> 6
# 25 : 2 5
# 2  : 0 2

digits_sum = 0
while N > 0:
    # print("N = ", N)
    # print("N % 10 ", N % 10)
    digits_sum += N % 10
    N = N // 10

print(digits_sum)



