import math


def table(f, *xs): # f - змінна функціонального типу
    for x in xs:
        print(f"f({x}) = { f(x) }")  # f(x) - виклик функції f для параметра x


######## MAIN

pi = math.pi

table(math.cos, 0, pi/6, pi/4, pi/3, pi/2 )  # використали опис функції з довільною кількістью параметрів, для визначення точок для побудови таблиці
