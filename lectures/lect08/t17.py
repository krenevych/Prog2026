
# ==== Опис підпрограми ====
def suma(*tpl):
    res = 0  # <== локальна змінна підпрограми suma
    for el in tpl:  # <== el - локальна змінна підпрограми
        res += el
    return res
# ==== Завершення опису підпрограми =====

#### MAIN #####

suma(1, 2, 3)

