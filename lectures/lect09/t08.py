# 1. Починаємо з термінальних випадків, тобто найпростіших,
# коли ми зразу можеш сказати відповідь
# якщо рядок складається з одного символа або порожній, то рядок симетричний
# "a", ""
# 2. Не термінальний: рядок симетричний, якщо перший і останній сиволи однакові і симетричним є рядок без першого і останнього символів

def is_sym(s):
    if len(s) <= 1:
        # print(s) # для дебагу
        return True
    else:
        # print(f"{s[0]} == {s[-1]} and {s[1:-1]}") # Для дебагу
        return s[0] == s[-1] and is_sym(s[1:-1])

