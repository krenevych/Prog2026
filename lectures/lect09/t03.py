# Дебагінг рекурсивної функції

def F(n):
    print(f"Заходимо у функцію при n={n}")
    if n == 0 or n == 1:
        print(f"Вихід ^ {n}")
        return 1
    else:
        print(f"Прямий хід рекурсії {n-1}, {n-2}")
        return F(n-1) + F(n-2)

###### MAIN ###############
print(
    F(5)
)